const splitWords = (text) => text.trim().split(/\s+/);

function Fireworks() {
  const canvasRef = useRef(null);
  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return undefined;

    const ctx = canvas.getContext("2d");
    if (!ctx) return undefined;

    let raf;
    let fireworks = [];
    let particles = [];
    const resize = () => {
      const dpr = Math.min(window.devicePixelRatio || 1, 2);
      canvas.width = Math.floor(window.innerWidth * dpr);
      canvas.height = Math.floor(window.innerHeight * dpr);
      canvas.style.width = `${window.innerWidth}px`;
      canvas.style.height = `${window.innerHeight}px`;
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    };
    resize();
    window.addEventListener("resize", resize);

    const launch = () => {
      fireworks.push({
        x: Math.random() * window.innerWidth,
        y: window.innerHeight + 10,
        tx: Math.max(40, Math.random() * (window.innerWidth - 80)),
        ty: 90 + Math.random() * window.innerHeight * 0.45,
        speed: 7 + Math.random() * 3
      });
    };
    const explode = (x, y) => {
      const count = 55 + Math.floor(Math.random() * 35);
      for (let i = 0; i < count; i++) {
        const a = Math.random() * Math.PI * 2;
        const s = 1.5 + Math.random() * 5;
        particles.push({
          x, y, vx: Math.cos(a) * s, vy: Math.sin(a) * s,
          life: 1, size: 1.5 + Math.random() * 2.5
        });
      }
    };

    const tick = () => {
      ctx.clearRect(0, 0, window.innerWidth, window.innerHeight);
      if (Math.random() < 0.055) launch();

      fireworks.forEach((f, i) => {
        const dx = f.tx - f.x, dy = f.ty - f.y;
        const d = Math.hypot(dx, dy) || 1;
        f.x += dx / d * f.speed; f.y += dy / d * f.speed;
        ctx.beginPath();
        ctx.arc(f.x, f.y, 2, 0, Math.PI * 2);
        ctx.fillStyle = "#fff";
        ctx.fill();
        if (d < 12) { explode(f.x, f.y); fireworks.splice(i, 1); }
      });

      particles.forEach((p, i) => {
        p.x += p.vx; p.y += p.vy; p.vy += 0.045; p.life -= 0.014;
        ctx.globalAlpha = Math.max(0, p.life);
        ctx.beginPath();
        ctx.arc(p.x, p.y, p.size, 0, Math.PI * 2);
        ctx.fillStyle = ["#ffd166","#ff4d9d","#7cf7ff","#b28dff","#ffffff"][i % 5];
        ctx.fill();
      });
      ctx.globalAlpha = 1;
      particles = particles.filter(p => p.life > 0);
      raf = requestAnimationFrame(tick);
    };
    tick();
    return () => {
      cancelAnimationFrame(raf);
      window.removeEventListener("resize", resize);
      ctx.clearRect(0, 0, window.innerWidth, window.innerHeight);
    };
  }, []);
  return <canvas ref={canvasRef} className="fireworks-canvas" />;
}

function Confetti({ active }) {
  const pieces = useMemo(() => Array.from({length: 95}, (_, i) => ({
    left: `${Math.random() * 100}%`,
    delay: `${Math.random() * 2.8}s`,
    duration: `${3 + Math.random() * 4}s`,
    rotate: `${Math.random() * 360}deg`,
    color: ["#ff4d9d","#ffd166","#7cf7ff","#9b7cff","#fff"][i % 5]
  })), []);
  if (!active) return null;
  return <div className="confetti">{pieces.map((p, i) =>
    <span key={i} style={{left:p.left, animationDelay:p.delay, animationDuration:p.duration, transform:`rotate(${p.rotate})`, background:p.color}} />
  )}</div>;
}

function WordReveal({ text, start }) {
  const words = splitWords(text);
  return (
    <div className="word-text">
      {words.map((word, i) => (
        <span key={i} className="word" style={{animationDelay: `${Math.min(i * 0.035, 7)}s`, animationPlayState: start ? "running" : "paused"}}>
          {word}
        </span>
      ))}
    </div>
  );
}

class AppErrorBoundary extends React.Component {
  constructor(props) {
    super(props);
    this.state = { hasError: false };
  }

  static getDerivedStateFromError() {
    return { hasError: true };
  }

  componentDidCatch(error) {
    console.error("ПоздравОК: ошибка приложения", error);
  }

  render() {
    if (this.state.hasError) {
      return (
        <main className="app error-screen">
          <section className="screen">
            <div className="timer-card glass">
              <div className="small-label">ПОЗДРАВОК</div>
              <h1>Что-то пошло не так</h1>
              <p>Перезагрузи страницу — приложение попробует запуститься снова.</p>
              <button className="btn btn-light next animated-button" onClick={() => window.location.reload()}>
                Перезагрузить
              </button>
            </div>
          </section>
        </main>
      );
    }
    return this.props.children;
  }
}

